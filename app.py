# -------------------- DEMO CONTROL --------------------
def demo_control():
    st.title("Demo Control")
    st.caption("Click these in order during the live walkthrough.")
    st.markdown("---")

    steps = [
        (
            "▶ End Session 4 (trigger Scribe)",
            "session_4_ended",
            "3 takeaway candidates surfaced in Therapist View.",
            None,
        ),
        (
            "▶ Therapist approves anchor",
            "takeaway_approved",
            "Anchor queued for Tuesday 7am delivery.",
            "session_4_ended",
        ),
        (
            "▶ Tuesday morning (deliver anchor)",
            "anchor_delivered",
            "Anchor card live in Patient View.",
            "takeaway_approved",
        ),
        (
            "▶ Friday — fire Pattern Alert",
            "pattern_alert_fired",
            "Circling alert visible to Dr. Chen.",
            None,
        ),
        (
            "▶ Monday — generate Session 5 Brief",
            "brief_generated",
            "Pre-session brief live at top of Therapist View.",
            "anchor_delivered",
        ),
    ]

    for label, flag, status_msg, dep in steps:
        with st.container(border=True):
            cols = st.columns([3, 4])
            with cols[0]:
                disabled = (dep is not None and not st.session_state[dep]) or st.session_state[flag]
                if st.button(label, disabled=disabled, key=f"btn_{flag}"):
                    st.session_state[flag] = True
                    st.rerun()
            with cols[1]:
                if st.session_state[flag]:
                    st.success(status_msg)
                else:
                    st.caption(status_msg)

    st.markdown("---")
    cc = st.columns(2)
    with cc[0]:
        if st.button("Reset demo", type="secondary"):
            for k in DEMO_FLAGS:
                st.session_state[k] = False
            st.rerun()
    with cc[1]:
        st.caption(
            "Tip: keep Therapist tab open in one window, Patient in another. "
            "Drive everything from this tab."
        )

    st.markdown("##### Live state")
    state_rows = [{"flag": k, "active": st.session_state[k]} for k in DEMO_FLAGS]
    st.dataframe(state_rows, use_container_width=True, hide_index=True)


