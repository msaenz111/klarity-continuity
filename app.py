# -------------------- THERAPIST VIEW --------------------
def therapist_view():
    st.markdown("### Good morning, Dr. Chen")
    st.caption("Monday, May 11 · 3 sessions today")
    st.markdown("")

    # Section A — Pre-session brief
    if st.session_state["brief_generated"]:
        brief = MOCK_AGENT_OUTPUTS["brief"]["brief"]
        st.markdown(
            f"""
            <div class="brief-card">
              <strong>Patient #247 · Session 5 · Tuesday 2:00pm</strong><br><br>
              {brief}
            </div>
            """,
            unsafe_allow_html=True,
        )
        st.caption("Generated by Brief Agent · you reviewed at 8:42am")
    else:
        st.markdown(
            """
            <div class="brief-card">
              <span class="small-muted">
                Brief for Patient #247 will appear here once Session 5 prep is generated.
              </span>
            </div>
            """,
            unsafe_allow_html=True,
        )

    st.markdown("")

    # Section B — Pattern Agent alert
    if st.session_state["pattern_alert_fired"]:
        pattern = MOCK_AGENT_OUTPUTS["pattern"]
        with st.expander(
            "  Circling pattern detected — work boundaries × 4 weeks",
            expanded=True,
        ):
            st.markdown(
                f"""
                <div class="pattern-card">
                  <strong>{pattern['topic']}</strong><br><br>
                  {pattern['recommendation']}
                </div>
                """,
                unsafe_allow_html=True,
            )
            st.markdown("**Suggested resources**")
            for r in pattern["resources"]:
                st.markdown(f"• **{r['title']}** — *{r['why']}*")
            st.markdown("")
            c1, c2, c3 = st.columns(3)
            with c1:
                st.button("Suggest a values exercise", key="pat_b1")
            with c2:
                st.button("Surface their own Session 2 quote", key="pat_b2")
            with c3:
                st.button("Dismiss", key="pat_b3")
            st.caption(
                "You decide. Klarity never messages your patient without your approval."
            )

    # Section C — Session 4 takeaway candidates
    if st.session_state["session_4_ended"] and not st.session_state["takeaway_approved"]:
        st.markdown("#### From Session 4 · Scribe Agent")
        st.caption(
            "In Patient #247's own words. Pick one to send as their anchor this week."
        )
        for i, t in enumerate(MOCK_AGENT_OUTPUTS["scribe"]["candidate_takeaways"]):
            st.markdown(
                f"""
                <div class="takeaway-card">
                  <div style="font-family:'Lora',Georgia,serif;font-size:20px;line-height:1.4;">
                    "{t['phrase']}."
                  </div>
                  <div class="small-muted" style="margin-top:8px;">
                    From: <em>"{t['source_quote']}"</em>
                  </div>
                </div>
                """,
                unsafe_allow_html=True,
            )
            cols = st.columns([1, 1, 4])
            with cols[0]:
                if st.button("Approve & send", key=f"approve_{i}"):
                    st.session_state["takeaway_approved"] = True
                    st.rerun()
            with cols[1]:
                st.button("Edit", key=f"edit_{i}")
        st.markdown("")

    elif st.session_state["takeaway_approved"]:
        st.success(
            "Anchor sent. Patient #247 will see *“I'm allowed to celebrate my wins”* Tuesday 7am."
        )

    # Section D — Drop-off risk
    st.markdown("#### Engagement")
    c1, c2, c3 = st.columns(3)
    with c1:
        st.metric("Sessions attended", "4 of 5", delta="−1 no-show")
    with c2:
        st.metric("Drop-off risk", "Moderate", delta="↓ from High")
    with c3:
        st.metric("Last engagement", "2 days ago", delta="anchor tapped")
    st.caption(
        "Risk model uses attendance + engagement + circling signals. Explainable on click."
    )


